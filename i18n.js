export function tdom(root=document){
  const walk=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  const nodes=[];
  while(walk.nextNode())nodes.push(walk.currentNode);
  for(const node of nodes){
    if(['SCRIPT','STYLE'].includes(node.parentElement?.tagName))continue;
    const value=node.nodeValue;
    const prev=originals.get(node);
    const source=prev && value===prev.last?prev.source:value;
    const text=source.trim();
    if(!translations[text])continue;
    const translated=source.replace(text,tr(text));
    node.nodeValue=translated;
    originals.set(node,{source,last:translated});
  }
  const elements=[root,...root.querySelectorAll?.('*')||[]];
  for(const element of elements){
    if(!(element instanceof Element))continue;
    for(const attr of attributes){
      if(!element.hasAttribute(attr))continue;
      const old=originals.get(element)?.[attr];
      const raw=element.getAttribute(attr);
      const original=old?.last===raw?old.source:raw;
      if(!translations[original])continue;
      const trans=tr(original);
      element.setAttribute(attr,trans);
      originals.set(element,{...originals.get(element),[attr]:{source:original,last:trans}});
    }
  }
  document.documentElement.lang=current;
  document.title=tr('დარჩა — დარჩენილი სამშენებლო მასალების ბაზარი');
}
export function setLang(value){
  current=['ka','en','ru'].includes(value)?value:'ka';
  try{localStorage.setItem('darcha-language',current)}catch{}
  tdom();
  document.dispatchEvent(new CustomEvent('darcha:languagechange'));
}
export function initLang(){
  let preferred='ka';
  try{preferred=localStorage.getItem('darcha-language')||'ka'}catch{}
  current=['ka','en','ru'].includes(preferred)?preferred:'ka';
  tdom();
  return current;
}

